class VerificationWritesNoEvidence(ScratchCase):
    """The rule this round added, asserted directly on the module's defaults.

    Every entry point a test may call must default to a path OUTSIDE evidence/.
    A future edit that restores an `evidence/...` default fails here, before the
    slower `CheckAllLeavesTheTreeClean` notices the churn.
    """

    def test_ensure_retained_record_does_not_touch_the_committed_record(self):
        with open(replay.RETAINED_PATH, "rb") as handle:
            before = handle.read()
        record = replay.ensure_retained_record()
        with open(replay.RETAINED_PATH, "rb") as handle:
            self.assertEqual(handle.read(), before)
        # ...and what it returns IS the committed record, not the rebuild.
        self.assertEqual(json.dumps(record, sort_keys=True),
                         json.dumps(json.loads(before.decode("utf-8")), sort_keys=True))

    def test_the_default_destinations_are_all_outside_the_evidence_tree(self):
        record = replay.ensure_retained_record()
        evidence = os.path.abspath(EVIDENCE) + os.sep
        produced = []

        scratch = self.scratch("defaults-")
        replay.ensure_retained_record(out_dir=scratch)
        produced.append(os.path.join(scratch, "retained.json"))

        report = replay.run_fresh_process_replay(record)  # no log_path
        self.assertEqual(report["failed_checks"], [])
        # run_tamper_check / run_registry_hole_check with no paths at all:
        tamper = replay.run_tamper_check(record)
        self.assertTrue(tamper["record_unchanged_by_baseline_replay"])
        replay.run_registry_hole_check(record)

        for path in produced:
            self.assertTrue(os.path.isfile(path))
            self.assertFalse(os.path.abspath(path).startswith(evidence), path)
        # The one committed file this class re-derives is unchanged on disk.
        self.assertTrue(os.path.isfile(replay.RETAINED_PATH))

    def test_owned_evidence_lists_every_committed_artifact_this_script_writes(self):
        """`replay.py --force` must be able to regenerate everything under its ownership;
        a committed artifact missing from OWNED_EVIDENCE is one nothing regenerates."""
        owned = {os.path.abspath(path) for path in replay.OWNED_EVIDENCE}
        on_disk = set()
        for root, _dirs, files in os.walk(replay.REPLAY_DIR):
            on_disk |= {os.path.abspath(os.path.join(root, name)) for name in files}
        for root, _dirs, files in os.walk(replay.TAMPER_DIR):
            on_disk |= {os.path.abspath(os.path.join(root, name)) for name in files}
        on_disk |= {
            os.path.abspath(replay.REGISTRY_HOLE_LOG),
            os.path.abspath(replay.DETERMINISM_LOG),
            os.path.abspath(replay.LF_DRIFT_LOG),
            os.path.abspath(replay.RETAINED_PATH),
        }
        self.assertEqual(sorted(on_disk - owned), [])

    def test_a_bare_replay_py_refuses_to_overwrite_committed_evidence(self):
        """Only `--force` may write under evidence/ (mirrors run.py:316-329)."""
        proc = subprocess.run(
            [sys.executable, os.path.join(HERE, "replay.py")],
            cwd=HERE, capture_output=True, text=True,
        )
        self.assertEqual(proc.returncode, 2, proc.stderr)
        self.assertIn("--force", proc.stderr)


class RetainedRecordIsDeterministic(ScratchCase):
    """Two independent builds of the Day 1 record are byte-identical, and they match
    the committed evidence/run-1/retained.json.

    replay.build_retained_record() re-derives the record from features.make_data
    with the fixed seed=7 (run.py main() default); nothing in the record depends
    on wall-clock time or process identity except the `retained.commit` stamp,
    which is a fact about the working tree rather than about the run
    (replay.unstamped explains why the oracle blanks it).
    """

    def test_two_independent_builds_are_byte_identical(self):
        first = json.dumps(replay.build_retained_record(), sort_keys=True)
        second = json.dumps(replay.build_retained_record(), sort_keys=True)
        self.assertEqual(first, second)

    def test_a_fresh_build_matches_the_committed_record_and_is_written_as_lf(self):
        scratch = self.scratch("retained-oracle-")
        committed = replay.ensure_retained_record(out_dir=scratch)
        produced_path = os.path.join(scratch, "retained.json")
        with open(produced_path, "rb") as handle:
            raw = handle.read()
        self.assertNotIn(b"\r\n", raw)
        self.assertEqual(
            json.dumps(replay.unstamped(json.loads(raw.decode("utf-8"))), sort_keys=True),
            json.dumps(replay.unstamped(committed), sort_keys=True),
        )

    def test_the_oracle_fails_when_the_record_really_differs(self):
        """Kills: an `ensure_retained_record` that compares nothing.

        A committed record with one digest changed must be refused, and the message
        must name the regeneration command rather than silently rewriting the file.
        """
        scratch = self.scratch("oracle-negative-")
        forged = copy.deepcopy(replay.ensure_retained_record())
        forged["results"]["split"] = "0" * 64
        fake_committed = retain.write_record(forged, os.path.join(scratch, "committed.json"))
        with unittest.mock.patch.object(replay, "RETAINED_PATH", fake_committed):
            with self.assertRaises(AssertionError) as caught:
                replay.ensure_retained_record(out_dir=self.scratch("oracle-negative-out-"))
        self.assertIn("replay.py --force", str(caught.exception))

    def test_the_committed_stamp_names_a_commit_git_knows(self):
        """The one field the oracle blanks is checked on its own terms."""
        committed = replay.ensure_retained_record()
        stamp = committed["retained"]["commit"]
        sha = stamp[: -len("-dirty")] if stamp.endswith("-dirty") else stamp
        self.assertRegex(sha, r"^[0-9a-f]{40}$")
        proc = subprocess.run(["git", "cat-file", "-e", f"{sha}^{{commit}}"], cwd=HERE)
        self.assertEqual(proc.returncode, 0, f"retained.commit names an unknown commit: {stamp}")

    def test_retained_program_ticks_equal_the_committed_day1_testimony_ticks(self):
        """evidence/run-1/testimony.json needs no conversion to become the program (gap 18d)."""
        record = replay.ensure_retained_record()
        with open(os.path.join(replay.RUN1, "testimony.json"), encoding="utf-8") as handle:
            testimony = json.load(handle)
        self.assertEqual(
            json.dumps(record["program"]["ticks"], sort_keys=True),
            json.dumps(testimony["ticks"], sort_keys=True),
        )

    def test_result_digests_agree_with_the_committed_comparison(self):
        record = replay.ensure_retained_record()
        with open(replay.COMPARISON_PATH, encoding="utf-8") as handle:
            committed = json.load(handle)
        _pxc, run = retain.replay(record, REGISTRY)
        self.assertEqual(run.results["compare"], committed["rows"])
        for invocation_id, digest in record["results"].items():
            self.assertEqual(digest, retain.digest_of(run.results[invocation_id]), invocation_id)


class ReplayObserveSeam(unittest.TestCase):
    """retain.replay(..., observe=True) is what lets a replay report receipts.

    Fixer round 3, finding 2: the fresh-process child now replays with the Day 2
    seam on and reports `Receipt.result_sha256` per invocation. These tests pin the
    seam itself, in-process, so a failure in the child is not the first place the
    break shows up.
    """

    def test_observe_off_yields_no_receipts_and_observe_on_covers_every_invocation(self):
        record = replay.ensure_retained_record()
        _pxc, plain = retain.replay(record, REGISTRY)
        self.assertEqual(dict(plain.receipts), {})
        _pxc, observed = retain.replay(record, REGISTRY, observe=True)
        self.assertEqual(sorted(observed.receipts), sorted(observed.results))

    def test_receipt_digests_equal_the_records_result_digests(self):
        record = replay.ensure_retained_record()
        _pxc, run = retain.replay(record, REGISTRY, observe=True)
        self.assertEqual(
            {k: r.result_sha256 for k, r in run.receipts.items()}, record["results"]
        )

    def test_testimony_bytes_are_identical_with_observe_on_and_off(self):
        """The day's hard rule, re-asserted through the replay path."""
        import dataclasses

        record = replay.ensure_retained_record()
        _pxc, plain = retain.replay(record, REGISTRY)
        _pxc, observed = retain.replay(record, REGISTRY, observe=True)
        self.assertEqual(
            json.dumps([dataclasses.asdict(t) for t in plain.ticks]),
            json.dumps([dataclasses.asdict(t) for t in observed.ticks]),
        )


class FreshProcessReplay(ScratchCase):
    """`python3 -I` from a cwd outside the repo, env stripped to PATH only."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.mkdtemp(prefix="fresh-process-")
        cls.log_path = os.path.join(cls.tmp, "fresh-process.log")
        cls.record = replay.ensure_retained_record()
        cls.report = replay.run_fresh_process_replay(cls.record, log_path=cls.log_path)
        with open(cls.log_path, "rb") as handle:
            cls.raw = handle.read()
        cls.text = cls.raw.decode("utf-8")

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def test_log_was_written_with_the_command_line_and_module_dump(self):
        self.assertNotIn(b"\r\n", self.raw)
        for marker in ("command:", "cwd (outside repo):", "sys.path before:", "sys.path after:", "sys.modules after replay", "new modules introduced"):
            self.assertIn(marker, self.text)

    def test_the_produced_log_matches_the_committed_one_line_for_line(self):
        """The oracle (fixer round 3, finding 1): this run wrote into a temp dir, and
        every meaning-bearing line agrees with evidence/replay/fresh-process.log.

        A stale committed log fails here naming the regeneration command, instead of
        being silently overwritten by the act of testing it.
        """
        self.assertEqual(
            replay.oracle_lines(self.text),
            replay.oracle_lines_of(replay.FRESH_PROCESS_LOG),
            "evidence/replay/fresh-process.log is stale; regenerate it with "
            "`python3 experiments/grouped-ablation/replay.py --force`",
        )

    def test_log_carries_the_checks_the_child_makes_before_trusting_the_record(self):
        """Kills: dropping any of the guards added in fixer rounds 1 and 3."""
        for marker in (
            "record program ticks identical to the committed evidence/run-1/testimony.json ticks: True",
            "equal the declared inputs",
            "provider identity accepted (retain.verify_provider): True",
            "calculations.py sha256 the record claims",
            "child failed checks: []",
        ):
            self.assertIn(marker, self.text)

    def test_the_terminal_line_is_the_verdict_and_it_accepted_this_record(self):
        """`child failed checks: []` is NOT the verdict (fixer round 2, finding 3)."""
        self.assertEqual(replay._verdict_line(self.log_path), "VERDICT: accepted")

    def test_the_child_neither_read_nor_wrote_bytecode(self):
        """`python3 -B` plus the parent's __pycache__ purge: a stale .pyc whose
        timestamp and size still match a tampered source cannot serve the replay."""
        self.assertTrue(self.report["dont_write_bytecode"])
        self.assertIn("-B", replay.run_fresh_process_replay.__doc__)
        self.assertIn("__pycache__ directories purged under the experiment before the spawn:", self.text)
        self.assertIn("child sys.dont_write_bytecode (python3 -B): True", self.text)

    def test_the_child_read_the_same_module_sources_the_parent_sees_on_disk(self):
        parent = replay._source_sha256(("retain.py", "calculations.py", "features.py"))
        self.assertEqual(self.report["source_sha256"], parent)
        self.assertEqual(
            self.report["claimed_provider_source_sha256"], [parent["calculations.py"]]
        )

    def test_provider_identity_was_compared_and_agreed(self):
        self.assertTrue(self.report["provider_agrees"])
        self.assertTrue(self.report["provider_pyto_agrees"])
        self.assertEqual(self.report["provider_disagreeing_addresses"], [])
        report = retain.verify_provider(self.record, REGISTRY)
        self.assertTrue(report["agrees"])
        self.assertEqual(sorted(report["registry"]), sorted(REGISTRY))

    def test_cwd_was_outside_the_repository(self):
        cwd_line = next(line for line in self.text.splitlines() if line.startswith("cwd (outside repo): "))
        cwd = cwd_line.split(": ", 1)[1]
        self.assertFalse(os.path.abspath(cwd).startswith(os.path.abspath(REPO) + os.sep))

    def test_env_was_stripped_to_path_only(self):
        env_line = next(line for line in self.text.splitlines() if line.startswith("env: "))
        # SystemRoot on Windows only: without it the child cannot start at all
        # (replay.py's STRIPPED_ENV). Nothing else may leak through.
        expected = sorted(["PATH"] + (["SystemRoot", "SystemDrive"] if os.name == "nt" else []))
        self.assertEqual(sorted(eval(env_line[len("env: "):])), expected)

    def test_exactly_one_intra_repo_path_was_inserted_and_it_is_this_directory(self):
        added = [p for p in self.report["sys_path_after"] if p not in self.report["sys_path_before"]]
        self.assertEqual(added, [HERE])


class ChildModuleTable(ScratchCase):
    """Finding 3: the leak check reads the child's FULL sys.modules.

    Before this round it read `set(after) - set(before)`, so anything already
    resident when the snippet started -- a site hook's package, or in the limit a
    pre-imported `calculations` -- was subtracted away before the check saw it. The
    allowed set is now the four experiment modules, the stdlib, and an explicitly
    enumerated startup-resident set.
    """

    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.mkdtemp(prefix="module-table-")
        cls.record = replay.ensure_retained_record()
        cls.report = replay.run_fresh_process_replay(
            cls.record, log_path=os.path.join(cls.tmp, "fresh-process.log")
        )

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def test_the_startup_resident_set_is_named_not_inferred(self):
        self.assertEqual(
            sorted(replay._STARTUP_RESIDENT_MODULES),
            ["__main__", "_distutils_hack", "sitecustomize"],
        )
        self.assertEqual(
            sorted(replay._EXPERIMENT_MODULES),
            ["calculations", "features", "pyto", "retain"],
        )
        self.assertTrue(replay._EXPERIMENT_MODULES <= replay._ALLOWED_TOP_LEVEL_MODULES)
        self.assertTrue(replay._STARTUP_RESIDENT_MODULES <= replay._ALLOWED_TOP_LEVEL_MODULES)

    def test_the_experiment_modules_are_absent_from_sys_modules_before(self):
        """The child started clean: nothing it is about to import was already there."""
        resident = replay._top_level(self.report["sys_modules_before"])
        for name in ("pyto", "calculations", "features", "retain"):
            self.assertNotIn(name, resident)

    def test_nothing_outside_the_allowed_set_is_in_the_full_module_table(self):
        leaked = sorted(
            replay._top_level(self.report["sys_modules"]) - replay._ALLOWED_TOP_LEVEL_MODULES
        )
        self.assertEqual(leaked, [])

    def test_every_startup_resident_top_level_name_is_stdlib_or_named(self):
        """Kills: an environment that grew a new startup resident nobody looked at."""
        extra = sorted(
            replay._top_level(self.report["sys_modules_before"])
            - replay._STARTUP_RESIDENT_MODULES
            - replay._STDLIB_TOP_LEVEL_MODULES
        )
        self.assertEqual(
            extra, [],
            "a module is resident before the child imports anything and is neither "
            "stdlib nor in replay._STARTUP_RESIDENT_MODULES; name it there on purpose",
        )

    def test_the_full_table_check_is_strictly_stronger_than_the_old_difference(self):
        """The old check subtracted `sys_modules_before` wholesale; this proves that
        subtraction hid real names -- _distutils_hack and sitecustomize are resident,
        are not stdlib, and would have been invisible to it."""
        before = replay._top_level(self.report["sys_modules_before"])
        hidden = sorted((before - replay._STDLIB_TOP_LEVEL_MODULES) - {"__main__"})
        if not hidden:
            # A named skip, not a pass: the property is only demonstrable where the
            # interpreter has a non-stdlib startup resident. Store Python on Windows
            # keeps its packages under a per-user path the stripped child cannot
            # resolve (no LOCALAPPDATA), so the child starts with stdlib only.
            self.skipTest("no non-stdlib startup resident in the stripped child")
        for name in hidden:
            self.assertIn(name, replay._STARTUP_RESIDENT_MODULES)
            self.assertNotIn(name, self.report["new_modules"])


