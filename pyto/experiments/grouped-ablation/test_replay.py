class LfSourceDriftProbe(unittest.TestCase):
    """The committed evidence of the one probe the suite must not run itself.

    `replay.run_lf_source_drift_probe` sets PYTHONPATH to a scratch copy of the `pyto`
    package, which experiments/CAPTURE.md forbids inside scripts/check_all.sh; it runs
    only from `python3 experiments/grouped-ablation/replay.py --force`. These tests read
    its committed log, and `record_results_sha256` makes a stale log fail here rather
    than drift unnoticed.
    """

    @classmethod
    def setUpClass(cls):
        with open(replay.LF_DRIFT_LOG, "rb") as handle:
            cls.raw = handle.read()
        cls.text = cls.raw.decode("utf-8")

    def test_log_is_lf_and_names_the_pythonpath_it_used(self):
        self.assertNotIn(b"\r\n", self.raw)
        self.assertIn("PYTHONPATH (scratch, removed after the run): ", self.text)
        self.assertIn("`python3 experiments/grouped-ablation/replay.py` ONLY", self.text)

    def test_no_test_module_in_this_directory_calls_the_probe(self):
        """The needles are assembled at run time so this file does not match itself."""
        needles = ["run_lf_source_drift" + "_probe(", "_run_lf_copy" + "_row("]
        checked = []
        for name in sorted(os.listdir(HERE)):
            if not (name.startswith("test_") and name.endswith(".py")):
                continue
            checked.append(name)
            with open(os.path.join(HERE, name), encoding="utf-8") as handle:
                source = handle.read()
            for needle in needles:
                self.assertNotIn(needle, source, f"{name} calls the LF probe")
        self.assertIn("test_replay.py", checked)
        # It is reachable from replay.main() -- the standalone entry point -- and only there:
        # exactly two occurrences in replay.py, one `def` and one call.
        with open(os.path.join(HERE, "replay.py"), encoding="utf-8") as handle:
            replay_source = handle.read()
        self.assertEqual(replay_source.count(needles[0]), 2)
        self.assertEqual(replay_source.count("def " + needles[0]), 1)

    def test_module_sources_drifted_by_construction_while_digests_did_not(self):
        for name in ("core.py", "pcr.py"):
            self.assertRegex(self.text, rf"{name} source sha256: .*differs_by_construction=True")
        self.assertIn("normalized sha256 equal to the record's provider digests: True", self.text)
        self.assertIn("replay result digests identical to run-1 despite the source-hash drift: True", self.text)
        self.assertIn("used editable install instead of the LF copy: False", self.text)

    def test_the_log_was_produced_against_the_current_retained_record(self):
        """A stale log (someone regenerated retained.json without re-running the probe)
        fails here, naming the command to re-run."""
        import hashlib

        record = replay.ensure_retained_record()
        expected = hashlib.sha256(
            json.dumps(record["results"], sort_keys=True, separators=(",", ":")).encode("utf-8")
        ).hexdigest()
        line = next(l for l in self.text.splitlines() if l.startswith("record_results_sha256"))
        self.assertEqual(
            line.split(": ", 1)[1], expected,
            "evidence/lf-source-drift.log is stale; re-run "
            "`python3 experiments/grouped-ablation/replay.py --force`",
        )


class CheckAllLeavesTheTreeClean(unittest.TestCase):
    """The property finding 1 asks for, asserted end to end.

    Running the suites that regenerate evidence must leave `git status --short`
    empty. This runs the two grouped-ablation test modules in a CHILD interpreter
    (so a failure here is about what they wrote, not about this process's state)
    and compares `git status --porcelain` for the evidence tree before and after.

    It cannot use the whole of `check_all.sh` -- that would recurse into this test
    -- so it runs exactly the suites that write: test_replay.py and
    test_second_experiment.py. Everything else check_all.sh runs writes nothing
    under `pyto/experiments/grouped-ablation/evidence/`.

    If the tree is ALREADY dirty when this starts (someone is mid-edit), the test
    compares before against after rather than demanding empty, so it reports what
    the suites changed and nothing else.
    """

    SUITES = ("test_replay.py", "test_second_experiment.py")

    def _status(self) -> list[str]:
        proc = subprocess.run(
            ["git", "status", "--porcelain", "--", EVIDENCE],
            cwd=HERE, capture_output=True, text=True, check=True,
        )
        return sorted(line for line in proc.stdout.splitlines() if line.strip())

    def test_running_the_evidence_writing_suites_changes_no_committed_file(self):
        before = self._status()
        env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"}
        env["GROUPED_ABLATION_NESTED"] = "1"  # read by the guard below
        proc = subprocess.run(
            [sys.executable, "-m", "unittest", "-v", *[s[: -len(".py")] for s in self.SUITES]],
            cwd=HERE, capture_output=True, text=True, env=env,
        )
        after = self._status()
        self.assertEqual(
            proc.returncode, 0,
            f"the nested suite run failed:\n{proc.stdout[-4000:]}\n{proc.stderr[-4000:]}",
        )
        self.assertEqual(
            after, before,
            "running test_replay.py / test_second_experiment.py modified committed "
            "evidence. Verification must write to a temp dir and compare against the "
            f"committed files (replay.py, 'Who may write under evidence/'). Changed:\n"
            + "\n".join(sorted(set(after) ^ set(before))),
        )


# The nested run above executes this module again; skip the recursion.
if os.environ.get("GROUPED_ABLATION_NESTED") == "1":
    CheckAllLeavesTheTreeClean = unittest.skip(  # noqa: F811
        "nested run: the outer CheckAllLeavesTheTreeClean is driving this process"
    )(CheckAllLeavesTheTreeClean)

if __name__ == "__main__":
    unittest.main()
